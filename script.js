function t() { return i18n[currentLang]; }

function createCard(mod) {
  const card = document.createElement('div');
  card.className = 'card';
  const desc = mod.description[currentLang] || mod.description.ar;

  card.innerHTML = `
    <img class="mod-img" src="${mod.image}" alt="${mod.name}" onerror="this.src='action-and-stuff.png'">
    <div class="card-body">
      <h2>${mod.name}</h2>
      <p class="meta">${t().by} <span class="dev-link" data-dev="${mod.developer}">${mod.developer}</span></p>
      <div class="badges-row">
        <span class="meta ver">${mod.version}</span>
        <span class="mc-badge">🎮 ${mod.mcVersion}</span>
      </div>
      <p class="desc">${desc}</p>
    </div>
    <a class="btn" href="${mod.link}" target="_blank" rel="noopener">${t().download}</a>
  `;

  card.addEventListener('click', (e) => {
    if (e.target.closest('.btn')) return;
    if (e.target.closest('.dev-link')) {
      openDevPage(e.target.closest('.dev-link').dataset.dev);
      return;
    }
    openModal(mod);
  });

  return card;
}

function getFilteredMods() {
  const q = searchBar.value.trim().toLowerCase();
  if (!q) return mods;
  return mods.filter(m =>
    m.name.toLowerCase().includes(q) ||
    m.developer.toLowerCase().includes(q) ||
    (m.mcVersion || '').toLowerCase().includes(q) ||
    (m.description[currentLang] || '').toLowerCase().includes(q) ||
    (m.description.ar || '').toLowerCase().includes(q) ||
    (m.description.en || '').toLowerCase().includes(q)
  );
}

function renderMods() {
  const list = getFilteredMods();
  container.innerHTML = '';
  if (list.length === 0) {
    noResults.style.display = 'block';
    return;
  }
  noResults.style.display = 'none';
  list.forEach(mod => container.appendChild(createCard(mod)));
}

function renderDevMods(list) {
  devModsContainer.innerHTML = '';
  list.forEach(mod => devModsContainer.appendChild(createCard(mod)));
}

function openDevPage(developer) {
  const list = mods.filter(m => m.developer === developer);
  devName.textContent = developer;
  devCount.textContent = `${list.length} ${t().modCount}`;

  const img = developers[developer];
  if (img) {
    devAvatar.src = img;
    devAvatar.alt = developer;
    devAvatar.style.display = 'block';
  } else {
    devAvatar.style.display = 'none';
  }

  renderDevMods(list);
  devPage.classList.add('open');
  document.body.style.overflow = 'hidden';
}

function closeDevPage() {
  devPage.classList.remove('open');
  document.body.style.overflow = '';
}

devBack.addEventListener('click', closeDevPage);

function openModal(mod) {
  modalTitle.textContent = mod.name;
  modalMeta.innerHTML = `
    ${mod.developer} • ${mod.version} • ${t().platform}<br>
    <span class="mc-badge" style="margin-top:8px;display:inline-block;">🎮 ${t().compatibleWith} ${mod.mcVersion}</span>
  `;

  const longD = mod.longDescription ? (mod.longDescription[currentLang] || mod.longDescription.ar) : '';
  const shortD = mod.description[currentLang] || mod.description.ar;
  modalDesc.innerHTML = shortD + (longD ? '<br><br>' + longD : '');

  modalDownload.href = mod.link;
  modalDownload.textContent = t().download;

  modalGallery.innerHTML = '';
  (mod.gallery || [mod.image]).forEach(src => {
    const img = document.createElement('img');
    img.src = src;
    img.alt = mod.name;
    img.onerror = () => { img.src = 'action-and-stuff.png'; };
    modalGallery.appendChild(img);
  });

  modalVideos.innerHTML = '';
  if (mod.videos && mod.videos.length > 0) {
    mod.videos.forEach(url => {
      const iframe = document.createElement('iframe');
      iframe.src = url;
      iframe.height = "200";
      iframe.allowFullscreen = true;
      iframe.loading = "lazy";
      modalVideos.appendChild(iframe);
    });
  } else {
    modalVideos.innerHTML = `<p style="color:#7a8085;font-size:0.85rem;">${t().noVideo}</p>`;
  }

  modal.classList.add('open');
  modal.style.display = 'flex';
  document.body.style.overflow = 'hidden';
}

function closeModal() {
  modal.classList.remove('open');
  modal.style.display = 'none';
  document.body.style.overflow = '';
}

modalClose.addEventListener('click', closeModal);
modal.addEventListener('click', (e) => {
  if (e.target === modal) closeModal();
});

function openDrawer() {
  drawer.classList.add('open');
  drawerOverlay.classList.add('open');
}

function closeDrawer() {
  drawer.classList.remove('open');
  drawerOverlay.classList.remove('open');
}

menuBtn.addEventListener('click', openDrawer);
drawerOverlay.addEventListener('click', closeDrawer);

function switchTab(tabId) {
  document.querySelectorAll('.tab-page').forEach(p => p.classList.remove('active'));
  document.querySelectorAll('.drawer-item').forEach(b => b.classList.remove('active'));

  document.getElementById(tabId).classList.add('active');
  document.querySelector(`.drawer-item[data-tab="${tabId}"]`).classList.add('active');

  searchBar.style.display = tabId === 'tabHome' ? 'block' : 'none';
  closeDrawer();
}

document.querySelectorAll('.drawer-item').forEach(btn => {
  btn.addEventListener('click', () => switchTab(btn.dataset.tab));
});

function applyLanguage(lang) {
  currentLang = lang;
  const tr = i18n[lang];

  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';

  document.title = tr.title;
  document.getElementById('pageTitle').textContent = tr.title;
  document.getElementById('searchBar').placeholder = tr.searchPlaceholder;
  document.getElementById('noResults').textContent = tr.noResults;
  document.getElementById('pageFooter').textContent = tr.footer + " • " + tr.appBy;
  document.getElementById('imagesTitle').textContent = tr.images;
  document.getElementById('videoTitle').textContent = tr.video;
  document.getElementById('devBack').textContent = tr.back;
  document.getElementById('splashSub').textContent = tr.splashSub;
  langToggle.textContent = tr.langButton;

  document.getElementById('navHome').textContent = tr.navHome;
  document.getElementById('navContact').textContent = tr.navContact;
  document.getElementById('navAbout').textContent = tr.navAbout;

  document.getElementById('contactTitle').textContent = tr.contactTitle;
  document.getElementById('contactDesc').textContent = tr.contactDesc;
  document.getElementById('contactEmailLabel').textContent = tr.contactEmailLabel;
  document.getElementById('contactWhatsappLabel').textContent = tr.contactWhatsappLabel;
  document.getElementById('contactYoutubeLabel').textContent = tr.contactYoutubeLabel;
  document.getElementById('contactInstagramLabel').textContent = tr.contactInstagramLabel;

  document.getElementById('aboutTitle').textContent = tr.aboutTitle;
  document.getElementById('aboutAppLabel').textContent = tr.aboutAppLabel;
  document.getElementById('aboutDevLabel').textContent = tr.aboutDevLabel;
  document.getElementById('aboutVersionLabel').textContent = tr.aboutVersionLabel;
  document.getElementById('changelogTitle').textContent = tr.changelogTitle;
  tr.changelog.forEach((txt, i) => {
    const el = document.getElementById('changelog' + (i + 1));
    if (el) el.textContent = txt;
  });

  closeModal();
  closeDevPage();
  renderMods();
}

langToggle.addEventListener('click', () => applyLanguage(currentLang === 'ar' ? 'en' : 'ar'));
searchBar.addEventListener('input', renderMods);

applyLanguage('ar');

